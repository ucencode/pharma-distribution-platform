import { eq } from "drizzle-orm";
import { afterAll, describe, expect, it } from "vitest";
import { closeDb, db } from "@/lib/db/client";
import { categories, inventory, products, warehouses } from "@/lib/db/schema";
import * as categoryList from "@/app/api/categories/route";
import * as categoryItem from "@/app/api/categories/[id]/route";
import * as productList from "@/app/api/products/route";
import * as productItem from "@/app/api/products/[id]/route";
import * as warehouseList from "@/app/api/warehouses/route";
import * as warehouseItem from "@/app/api/warehouses/[id]/route";
import * as inventoryList from "@/app/api/inventory/route";
import * as inventoryItem from "@/app/api/inventory/[warehouseId]/[productId]/route";

// IDs are generated by the database. The first test of each resource stores the ID it
// gets back, later tests use it, and afterAll deletes the records by these IDs.
const ids = { category: "", product: "", warehouse: "" };

const json = (body: unknown) =>
  new Request("http://test", {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: typeof body === "string" ? body : JSON.stringify(body),
  });
const empty = new Request("http://test");
const params = <T extends object>(p: T) => ({ params: Promise.resolve(p) });

async function cleanUp() {
  await db.delete(inventory).where(eq(inventory.warehouseId, ids.warehouse));
  await db.delete(products).where(eq(products.id, ids.product));
  await db.delete(warehouses).where(eq(warehouses.id, ids.warehouse));
  await db.delete(categories).where(eq(categories.id, ids.category));
}

afterAll(async () => {
  await cleanUp();
  await closeDb();
});

describe("categories", () => {
  const ctx = () => params({ id: ids.category });

  it("creates a category with a generated ID", async () => {
    const created = await categoryList.POST(json({ name: "Test Category" }));
    expect(created.status).toBe(201);
    const row = await created.json();
    expect(row.id).toMatch(/^C\d{2,}$/);
    ids.category = row.id;
  });

  it("ignores an ID sent by the client", async () => {
    const created = await categoryList.POST(json({ id: "TEST-C1", name: "Test Category X" }));
    const row = await created.json();
    expect(row.id).not.toBe("TEST-C1");
    await db.delete(categories).where(eq(categories.id, row.id));
  });

  it("reads, lists and updates a category", async () => {
    const read = await categoryItem.GET(empty, ctx());
    expect(await read.json()).toEqual({ id: ids.category, name: "Test Category" });

    const list = await (await categoryList.GET()).json();
    expect(list).toContainEqual({ id: ids.category, name: "Test Category" });

    const updated = await categoryItem.PATCH(json({ name: "Test Category 2" }), ctx());
    expect(await updated.json()).toEqual({ id: ids.category, name: "Test Category 2" });
  });

  it("rejects invalid input, empty updates and duplicate names", async () => {
    expect((await categoryList.POST(json({ name: "" }))).status).toBe(400);
    expect((await categoryList.POST(json("not json"))).status).toBe(400);
    expect((await categoryItem.PATCH(json({}), ctx())).status).toBe(400);
    expect((await categoryList.POST(json({ name: "Test Category 2" }))).status).toBe(409);
  });

  it("returns 404 for a missing category", async () => {
    const missing = params({ id: "TEST-MISSING" });
    expect((await categoryItem.GET(empty, missing)).status).toBe(404);
    expect((await categoryItem.PATCH(json({ name: "X" }), missing)).status).toBe(404);
    expect((await categoryItem.DELETE(empty, missing)).status).toBe(404);
  });
});

describe("products", () => {
  const ctx = () => params({ id: ids.product });

  it("creates a product with a generated ID and the default cold-chain flag", async () => {
    const res = await productList.POST(json({ name: "Test Product", categoryId: ids.category }));
    expect(res.status).toBe(201);
    const row = await res.json();
    expect(row.id).toMatch(/^P\d{3,}$/);
    ids.product = row.id;
    expect(row).toEqual({
      id: ids.product,
      name: "Test Product",
      categoryId: ids.category,
      requiresColdChain: false,
    });
  });

  it("reads, lists and updates a product", async () => {
    expect((await productItem.GET(empty, ctx())).status).toBe(200);

    const list = await (await productList.GET()).json();
    expect(list.map((p: { id: string }) => p.id)).toContain(ids.product);

    const updated = await (await productItem.PATCH(json({ requiresColdChain: true }), ctx())).json();
    expect(updated.requiresColdChain).toBe(true);
    expect(updated.name).toBe("Test Product");
  });

  it("rejects an unknown category", async () => {
    const res = await productList.POST(json({ name: "Test Product X", categoryId: "TEST-MISSING" }));
    expect(res.status).toBe(409);
  });

  it("does not delete a category that a product uses", async () => {
    expect((await categoryItem.DELETE(empty, params({ id: ids.category }))).status).toBe(409);
  });
});

describe("warehouses", () => {
  const ctx = () => params({ id: ids.warehouse });

  it("creates, reads, lists and updates a warehouse", async () => {
    const created = await warehouseList.POST(json({ city: "Test City", distanceToCustomerKm: 12.5 }));
    expect(created.status).toBe(201);
    const row = await created.json();
    expect(row.id).toMatch(/^W\d{2,}$/);
    ids.warehouse = row.id;
    expect(row).toEqual({
      id: ids.warehouse,
      city: "Test City",
      distanceToCustomerKm: 12.5,
      hasColdStorage: false,
      hasRefrigeratedFleet: false,
    });

    expect((await warehouseItem.GET(empty, ctx())).status).toBe(200);

    const list = await (await warehouseList.GET()).json();
    expect(list.map((w: { id: string }) => w.id)).toContain(ids.warehouse);

    const updated = await (await warehouseItem.PATCH(json({ hasColdStorage: true }), ctx())).json();
    expect(updated.hasColdStorage).toBe(true);
  });

  it("rejects a negative distance", async () => {
    const res = await warehouseList.POST(json({ city: "Test City X", distanceToCustomerKm: -1 }));
    expect(res.status).toBe(400);
  });
});

describe("inventory", () => {
  const ctx = () => params({ warehouseId: ids.warehouse, productId: ids.product });

  it("creates, reads, lists and updates a stock row", async () => {
    const key = { warehouseId: ids.warehouse, productId: ids.product };
    const created = await inventoryList.POST(json({ ...key, quantity: 10 }));
    expect(created.status).toBe(201);

    const read = await (await inventoryItem.GET(empty, ctx())).json();
    expect(read).toMatchObject({ ...key, quantity: 10 });

    const list = await (await inventoryList.GET()).json();
    expect(list).toContainEqual(expect.objectContaining(key));

    const updated = await (await inventoryItem.PATCH(json({ quantity: 25 }), ctx())).json();
    expect(updated.quantity).toBe(25);
  });

  it("rejects invalid quantities, duplicates and unknown references", async () => {
    expect((await inventoryItem.PATCH(json({ quantity: -1 }), ctx())).status).toBe(400);
    expect((await inventoryItem.PATCH(json({ quantity: 1.5 }), ctx())).status).toBe(400);

    const row = { warehouseId: ids.warehouse, productId: ids.product, quantity: 1 };
    expect((await inventoryList.POST(json(row))).status).toBe(409);
    expect((await inventoryList.POST(json({ ...row, warehouseId: "TEST-MISSING" }))).status).toBe(409);
  });

  it("does not delete a product or warehouse that has stock", async () => {
    expect((await productItem.DELETE(empty, params({ id: ids.product }))).status).toBe(409);
    expect((await warehouseItem.DELETE(empty, params({ id: ids.warehouse }))).status).toBe(409);
  });
});

describe("deletes", () => {
  it("deletes the stock row, product, warehouse and category in order", async () => {
    const stock = params({ warehouseId: ids.warehouse, productId: ids.product });
    expect((await inventoryItem.DELETE(empty, stock)).status).toBe(204);
    expect((await inventoryItem.GET(empty, stock)).status).toBe(404);

    const product = params({ id: ids.product });
    expect((await productItem.DELETE(empty, product)).status).toBe(204);
    expect((await productItem.GET(empty, product)).status).toBe(404);

    const warehouse = params({ id: ids.warehouse });
    expect((await warehouseItem.DELETE(empty, warehouse)).status).toBe(204);
    expect((await warehouseItem.GET(empty, warehouse)).status).toBe(404);

    const category = params({ id: ids.category });
    expect((await categoryItem.DELETE(empty, category)).status).toBe(204);
    expect((await categoryItem.GET(empty, category)).status).toBe(404);
  });
});
